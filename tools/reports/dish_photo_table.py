#!/usr/bin/env python3
"""RR Durbar task 1.1: dish-photo reference table, built by script from public/index.html. Read-only; changes nothing.
Run from the website repo root:  python3 tools/reports/dish_photo_table.py [public/index.html] > docs/dish-photo-table.md
It lists, for every dish photo the site uses: the menu (Rista) name, the name shown on the card (rename layer RRDN, task 1.3),
the image file, and every place that references that file. Then it flags what a person must look at:
  RENAMED   the card now shows a different dish name than the one the photo was made for (check the photo shows the new dish)
  SHARED    one image file is used for more than one dish
  SPLIT     one dish uses different image files in different places
Missing files and file sizes are NOT checked here (that is imgcheck.js / the site gate, which need the image folder)."""
import html, json, re, sys
from collections import defaultdict
from pathlib import Path

path = Path(sys.argv[1] if len(sys.argv) > 1 else 'public/index.html')
s = path.read_text(encoding='utf-8')
norm = lambda x: re.sub(r'\s+', ' ', html.unescape(x).strip().lower().replace('’', "'"))

def objects(name):
    out = []
    for m in re.finditer(name + r'\s*=\s*(\{[^{}]*\})', s):
        try: out.append(json.loads(m.group(1)))
        except Exception: pass
    return out

# Rename layer (task 1.3): Rista name -> display name, for Home signature cards and Menu cards
rrdn = {}
m = re.search(r'id="rr-display-names">(.*?)</script>', s, re.S)
if m:
    for obj in re.findall(r'\{[^{}]*\}', m.group(1)):
        try:
            for k, v in json.loads(obj).items(): rrdn.setdefault(norm(k), v)
        except Exception: pass

rows = []   # (dish, file, place)
for d in objects('RR_SIG_IMG'):
    for k, v in d.items(): rows.append((norm(k), v, 'Home signature cards / Order picks (RR_SIG_IMG)'))
for d in objects('RR_CAT_IMG'):
    for k, v in d.items(): rows.append((norm(k), v, 'Category image (RR_CAT_IMG)'))
m = re.search(r'var IM=\{\};\[(.*?)\]\.forEach', s, re.S)
if m:
    for slug in json.loads('[' + m.group(1) + ']'):
        rows.append((slug.replace('-', ' '), f'images/menu/{slug}.webp', 'Menu page image cards (IM list)'))
for m in re.finditer(r'<div class="hero-eyebrow">([^<]+)</div>', s):
    seg = s[max(0, m.start() - 1500):m.start()]
    imgs = re.findall(r'(?:data-card|data-thumb|src)="([^"]+\.(?:webp|jpg|png))"', seg)
    if imgs: rows.append((norm(m.group(1).split('·')[0]), ' + '.join(dict.fromkeys(imgs[-3:])), 'Home hero slide (one photo, 3 sizes)'))
for m in re.finditer(r'<img[^>]*?src="([^"]+\.(?:webp|jpg|png))"[^>]*?alt="([^"]{3,80})"', s):
    f, alt = m.group(1), m.group(2)
    if re.search(r'biryani|chicken|mutton|paneer|fish|prawn|egg|kebab|wings|vepudu|pulao|noodles|rice|tikka|curry', alt, re.I):
        rows.append((norm(alt), f, 'Image with dish alt text'))

by_file, by_dish = defaultdict(set), defaultdict(set)
places = defaultdict(set)
for dish, f, place in rows:
    by_file[f].add(dish); by_dish[dish].add(f); places[(dish, f)].add(place)

def shown(dish):
    for k, v in rrdn.items():
        if k == dish or k.replace("'", '') == dish.replace("'", ''): return v
    return ''

flags_total = defaultdict(int)
print('# RR Durbar dish-photo reference table (task 1.1)\n')
print(f'Source: `public/index.html` ({path.name}). Generated by `tools/reports/dish_photo_table.py`. Read-only.\n')
print('| Dish (menu / Rista name) | Card shows | Image file | Used in | Flags |\n|---|---|---|---|---|')
for (dish, f) in sorted(places):
    sh = shown(dish); fl = []
    if sh and norm(sh) != dish: fl.append('RENAMED')
    if len(by_file[f]) > 1: fl.append('SHARED')
    if len(by_dish[dish]) > 1: fl.append('SPLIT')
    for x in fl: flags_total[x] += 1
    print(f"| {dish} | {sh or '(same)'} | `{f}` | {'; '.join(sorted(places[(dish, f)]))} | {' '.join(fl)} |")
print(f"\n**Totals:** {len(places)} dish-photo pairs, {len(by_file)} image files, {len(by_dish)} dish names. "
      f"RENAMED {flags_total['RENAMED']}, SHARED {flags_total['SHARED']}, SPLIT {flags_total['SPLIT']}.")
print('\n**What to do with the flags (owner, by eye on a phone):** RENAMED = does the photo really show the new name? '
      'SHARED = is one photo standing in for two different dishes? SPLIT = should the dish use one photo everywhere? '
      'Nothing is renamed or moved until the owner answers (plan 1.1: "nothing is renamed before this table exists").')
