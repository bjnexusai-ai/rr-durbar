"""Phase 3, task 3.1 step A: build one real HTML file per page FROM public/index.html, so Google gets each page at its own address.
Run from the website repo root:   python3 tools/split/split_pages.py            (writes public/<route>/index.html)
                                   python3 tools/split/split_pages.py --check    (writes nothing, prints what it would do)
public/index.html itself is NOT changed (step B, the home page and the ?page= redirects, is a separate change after preview).
Each page file is today's file with:
  - only its own sections: every other section[id] is removed (exactly what the browser already hides today). The site's
    scripts check for their section before they run, and its CSS only reacts to VISIBLE sections, so nothing else changes;
  - its own <title>, description, canonical https://rrdurbar.com/<route>/, Open Graph title/description/url (from pageSeo);
  - robots noindex on the order pages (order-now, pickup, pickup-menu, track-order), index,follow on the rest;
  - <base href="/"> so every relative image, script and link keeps working from /<route>/;
  - links of the old ?page=X kind rewritten to /X/ (home: /), keeping ?category= and #section;
  - the page router told which page it is (window.RR_PAGE), and links to OTHER pages made real page loads.
Run again after every change to public/index.html (the files are generated: never edit them by hand)."""
