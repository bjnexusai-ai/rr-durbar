# Pages whose main heading is an h2 in the one-page site: on their own page it becomes the one h1 (Google), same look.
H1_FROM_H2 = {'loyalty': ('<h2 id="lc-h">', '#loyalty .lc-head h2')}

def promote_h1(s, route):
    if route not in H1_FROM_H2: return s
    tag, css = H1_FROM_H2[route]
    i = s.find(tag)
    if i < 0 or s.count(tag) != 1: sys.exit(f'STOP: heading {tag} not found exactly once for {route}')
    j = s.index('</h2>', i)
    s = s[:i] + '<h1' + s[i + 3:j] + '</h1>' + s[j + 5:]
    if css not in s: sys.exit(f'STOP: heading style {css} not found')
    return s.replace(css + '{', css + ',' + css[:-2] + 'h1{').replace(css + ' em{', css + ' em,' + css[:-2] + 'h1 em{').replace(css + ' em::after{', css + ' em::after,' + css[:-2] + 'h1 em::after{')

def build(src, route, sections_for, seo):
    keep = set(sections_for[route])
    secs = Sections(src).found
    # outermost sections to blank: not on this page, and not inside another blanked section
    blank = sorted([s for s in secs if s['id'] not in keep], key=lambda s: s['start'])
    chosen, last_end = [], -1
    for s in blank:
        if s['start'] < last_end: continue
        chosen.append(s); last_end = s['end']
    out, pos = [], 0
    for s in chosen:
        out.append(src[pos:s['start']])
        out.append(f'<!-- #{s["id"]}: on {path_for(OWNER.get(s["id"], "home"))} -->')
        pos = s['end']
    out.append(src[pos:])
    s = ''.join(out)
    for old, new in ROUTER_PATCHES:
        if s.count(old) != 1: sys.exit(f'STOP: router line not found exactly once (public/index.html changed?): {old[:70]}')
        s = s.replace(old, new)
    s = rewrite_page_links(s)
    s = promote_h1(s, route)
    head_end = s.index('</head>')
    head, body = s[:head_end], s[head_end:]
    d = seo.get(route) or {}
    title, desc, url = d.get('title') or f'{route} | RR Durbar', d.get('desc') or '', SITE + path_for(route)
    head, n = re.subn(r'<title>.*?</title>', f'<title>{html.escape(title)}</title>', head, count=1, flags=re.S)
    if n != 1: sys.exit('STOP: <title> not found')
    head = set_meta(head, 'name', 'description', desc)
    head = set_meta(head, 'property', 'og:title', title)
    head = set_meta(head, 'property', 'og:description', desc)
    head = set_meta(head, 'property', 'og:url', url)
    head = set_meta(head, 'name', 'robots', 'noindex,follow' if route in NOINDEX else 'index,follow')
    head, n = re.subn(r'<link rel="canonical" href="[^"]*"\s*/?>', f'<link rel="canonical" href="{url}"/>', head, count=1)
    if n != 1: sys.exit('STOP: canonical link not found')
    head = re.sub(r'(<head[^>]*>)', r'\1\n' + MARK + f'\n<base href="/">\n<script>window.RR_PAGE={json.dumps(route)};</script>' + (FWD if route == 'home' else ''), head, count=1)
    return head + body

def main():
    check = '--check' in sys.argv
    if not SRC.exists(): sys.exit('STOP: src/site.html not found. Run from the website repo root')
    src = SRC.read_text(encoding='utf-8')
    if MARK in src: sys.exit('STOP: public/index.html looks generated')
    sections_for, seo = page_sections(src), page_seo(src)
    for r, ids in sections_for.items():
        for i in ids: OWNER.setdefault(i, 'about-us' if r == 'our-story' else r)
    total = 0
    for route in sections_for:
        if route in SKIP: continue
        page = build(src, route, sections_for, seo)
        f = Path('public/index.html') if route == 'home' else Path('public') / route / 'index.html'
        total += len(page)
        if check: print(f'would write {f} ({len(page):,} bytes, sections: {", ".join(sections_for[route])})'); continue
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(page, encoding='utf-8')
        print(f'wrote {f} ({len(page):,} bytes)')
    print(('CHECK ONLY: ' if check else 'DONE: ') + f'{sum(1 for r in sections_for if r not in SKIP)} pages, {total:,} bytes. home written to public/index.html.')

if __name__ == '__main__':
    main()
