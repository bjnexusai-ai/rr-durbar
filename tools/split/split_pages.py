def page_sections(src):
    m = re.search(r"const pageSections = (\{.*?\n  \});", src, re.S)
    if not m: sys.exit('STOP: pageSections not found in public/index.html')
    out = {}
    for k, v in re.findall(r"^\s*'?([a-z-]+)'?:\s*\[([^\]]*)\]", m.group(1), re.M):
        out[k] = re.findall(r"'([^']+)'", v)
    return out

def page_seo(src):
    i = src.find('const pageSeo = {')
    if i < 0: sys.exit('STOP: pageSeo not found')
    obj, _ = json.JSONDecoder().raw_decode(src[i + len('const pageSeo = '):])
    return obj

class Sections(HTMLParser):
    """Character ranges of every <section id=...> element, with nesting."""
    def __init__(self, src):
        super().__init__(convert_charrefs=False)
        self.src = src; self.lines = [0]
        for m in re.finditer('\n', src): self.lines.append(m.end())
        self.stack, self.found = [], []
        self.feed(src); self.close()
    def off(self): l, c = self.getpos(); return self.lines[l - 1] + c
    def handle_starttag(self, tag, attrs):
        if tag != 'section': return
        start = self.off(); end_of_tag = self.src.index('>', start) + 1
        a = dict(attrs); self.stack.append((a.get('id'), a.get('class') or '', start, end_of_tag))
    def handle_endtag(self, tag):
        if tag != 'section' or not self.stack: return
        sid, cls, start, eot = self.stack.pop()
        close = self.off(); end = self.src.index('>', close) + 1
        if sid: self.found.append({'id': sid, 'class': cls, 'start': start, 'end': end, 'depth': len(self.stack)})

def set_meta(head, attr, key, value):
    pat = re.compile(r'<meta\s+%s="%s"\s+content="[^"]*"\s*/?>' % (attr, re.escape(key)))
    tag = f'<meta {attr}="{key}" content="{html.escape(value, quote=True)}">'
    if pat.search(head): return pat.sub(lambda _: tag, head, count=1)
    return head.replace('</title>', '</title>\n' + tag, 1)

def path_for(route): return '/' if route == 'home' else f'/{route}/'

def rewrite_page_links(s):
    # href="?page=menu&category=x#y" or href="/?page=menu#y" or href="index.html?page=..."  ->  href="/menu/?category=x#y"
    def fix(m):
        q, attr = m.group(2), m.group(1)
        hashpart = ''
        if '#' in q: q, hashpart = q.split('#', 1); hashpart = '#' + hashpart
        params = [p for p in q.split('&') if p]
        route = next((p.split('=', 1)[1] for p in params if p.startswith('page=')), 'home')
        route = 'about-us' if route == 'our-story' else route
        rest = '&'.join(p for p in params if not p.startswith('page='))
        return f'{attr}="{path_for(route)}{("?" + rest) if rest else ""}{hashpart}"'
    return re.sub(r'(href)="(?:/|index\.html)?\?((?:[^"#]*&)?page=[^"]*)"', fix, s)

