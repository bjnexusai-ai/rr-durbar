#!/usr/bin/env python3
"""Proves the split pages look and behave like today's site. Run from the website repo root (needs Python Playwright + Chromium):
    python3 tools/split/compare_split.py public [route ...]
For every page it opens TODAY's view (/?page=<route>) and the NEW file (/<route>/) in a real browser, at phone (390x844) and
desktop (1280x800) size, and compares: the visible text, script errors, broken images, and a screenshot of the first screen.
It also clicks the first link to another page on the new file and checks that it lands on that page's own address.
Exit 0 = every page matches. The outside API is blocked in both views alike, so menus that load live data show the same fallback."""
import http.server, socketserver, sys, threading, functools, re
from pathlib import Path
from playwright.sync_api import sync_playwright

ROOT = Path(sys.argv[1] if len(sys.argv) > 1 else 'public').resolve()
ROUTES = sys.argv[2:] or [p.parent.name for p in sorted(ROOT.glob('*/index.html')) if 'generated by tools/split' in p.read_text(encoding='utf-8', errors='ignore')[:400]]
SIZES = [(390, 844), (1280, 800)]

class Quiet(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *a): pass

def serve():
    h = functools.partial(Quiet, directory=str(ROOT))
    s = socketserver.ThreadingTCPServer(('127.0.0.1', 0), h); s.daemon_threads = True
    threading.Thread(target=s.serve_forever, daemon=True).start()
    return s, f'http://127.0.0.1:{s.server_address[1]}'

def look(page, url):
    errs = []
    page.on('pageerror', lambda e: errs.append(str(e).split('\n')[0][:140]))
    page.goto(url, wait_until='load'); page.wait_for_timeout(1800)
    text = page.evaluate("() => document.body.innerText")
    broken = page.evaluate("() => [...document.images].filter(i => i.offsetParent && i.complete && i.naturalWidth === 0 && i.getAttribute('src') && !/^https?:/.test(i.getAttribute('src'))).map(i => i.getAttribute('src')).slice(0,5)")
    shot = page.screenshot()
    page.remove_listener('pageerror', page.listeners('pageerror')[0]) if hasattr(page, 'listeners') else None
    return re.sub(r'\s+', ' ', text).strip(), sorted(set(errs)), broken, shot

def same_shot(a, b):
    from PIL import Image, ImageChops
    import io
    x, y = Image.open(io.BytesIO(a)).convert('RGB'), Image.open(io.BytesIO(b)).convert('RGB')
    if x.size != y.size: return False, 100.0
    diff = ImageChops.difference(x, y).convert('L').point(lambda v: 255 if v > 40 else 0)
    pct = 100.0 * sum(1 for v in diff.getdata() if v) / (x.size[0] * x.size[1])
    return pct < 1.0, pct

def main():
    srv, base = serve()
    bad = 0
    with sync_playwright() as p:
        b = p.chromium.launch()
        for w, h in SIZES:
            ctx = b.new_context(viewport={'width': w, 'height': h}, reduced_motion='reduce')
            ctx.route(re.compile(r'^https?://(?!127\.0\.0\.1)'), lambda r: r.abort())   # outside world blocked in both views
            for r in ROUTES:
                old = look(ctx.new_page(), f'{base}/?page={r}')
                new = look(ctx.new_page(), f'{base}/{r}/')
                ok_text = old[0] == new[0]
                new_errs = [e for e in new[1] if e not in old[1]]
                ok_shot, pct = same_shot(old[3], new[3])
                ok = ok_text and not new_errs and not new[2] and ok_shot
                bad += 0 if ok else 1
                print(f"{'PASS' if ok else 'FAIL'}  {w}px {r:22s} text {'same' if ok_text else 'DIFFERENT'}  new errors {len(new_errs)}  broken images {len(new[2])}  first screen {pct:.2f}% different")
                if not ok_text:
                    o, n = old[0], new[0]
                    i = next((k for k in range(min(len(o), len(n))) if o[k] != n[k]), min(len(o), len(n)))
                    print(f"      today: ...{o[max(0, i - 60):i + 80]!r}\n      new:   ...{n[max(0, i - 60):i + 80]!r}")
                for e in new_errs: print('      new script error:', e)
                for s in new[2]: print('      broken image:', s)
            ctx.close()
        # navigation: a link to another page is a real page load to that page's own address
        ctx = b.new_context(viewport={'width': 1280, 'height': 800}); ctx.route(re.compile(r'^https?://(?!127\.0\.0\.1)'), lambda r: r.abort())
        pg = ctx.new_page(); pg.goto(f'{base}/menu/', wait_until='load'); pg.wait_for_timeout(800)
        pg.evaluate("() => window.rrGo('?page=catering#catering')"); pg.wait_for_load_state('load'); pg.wait_for_timeout(600)
        ok_nav = pg.url.startswith(f'{base}/catering/') and pg.evaluate("() => window.RR_PAGE") == 'catering'
        pg.goto(f'{base}/menu/', wait_until='load'); pg.wait_for_timeout(600)
        pg.evaluate("() => window.rrGo('?page=pickup-menu&outlet=moghalrajpuram')"); pg.wait_for_load_state('load'); pg.wait_for_timeout(600)
        ok_q = '/pickup-menu/?outlet=moghalrajpuram' in pg.url
        bad += 0 if (ok_nav and ok_q) else 1
        print(f"{'PASS' if ok_nav else 'FAIL'}  menu -> catering link lands on /catering/ ({pg.url if not ok_nav else 'ok'})")
        print(f"{'PASS' if ok_q else 'FAIL'}  pickup link keeps ?outlet= ({pg.url})")
        b.close()
    srv.shutdown()
    print(f'RESULT: {"all pages match" if not bad else str(bad) + " problem(s)"}')
    sys.exit(1 if bad else 0)

if __name__ == '__main__':
    main()
